// Методы массивов
// push - добавляет элемент в конец массива
// pop - удаляет последний элемент массива и возвращает его
// unshift - добавляет элемент в начало массива
// shift - удаляет первый элемент массива и возвращает его
// includes - проверяет наличие элемента в массиве и возвращает true или false
// indexOf - возвращает индекс элемента в массиве или -1, если элемент не найден
// slice - возвращает новый массив, содержащий копию части исходного массива
// splice - изменяет содержимое массива, удаляя или заменяя существующие элементы и/или добавляя новые элементы на месте
// join - объединяет все элементы массива в строку, используя указанный разделитель
// split - разбивает строку на массив подстрок, используя указанный разделитель
// forEach - выполняет указанную функцию один раз для каждого элемента массива
// map - создает новый массив с результатом вызова указанной функции для каждого элемента массива
// filter - создает новый массив со всеми элементами, которые прошли проверку, задаваемую в передаваемой функции

let productList = ["хлеб", "молоко", "яйца"];

// push - добавляет элемент в конец массива
productList.push("масло");
// unshift - добавляет элемент в начало массива
productList.unshift("сахар");
console.log(productList);

// slice - возвращает новый массив, содержащий копию части исходного массива
// Аргументы: начальный индекс (включительно), конечный индекс (не включительно)

let slicedProductList = productList.slice(1, 4);
console.log(slicedProductList);

let slicedProductList1 = productList.slice(1, productList.length);
console.log(slicedProductList1);

// splice - изменяет содержимое массива, удаляя или заменяя существующие элементы и/или добавляя новые элементы на месте
// Аргументы: начальный индекс, количество удаляемых элементов, элементы для добавления

// Добавим элемент "сыр" на позицию 2
productList.splice(2, 0, "сыр");
console.log(productList);

// Удалим элемент на позиции 3
productList.splice(3, 1);
console.log(productList);

// Удаление 2х элементов, начиная с позиции 1, и добавление "колбаса" на их место
productList.splice(1, 2, "колбаса");
console.log(productList);

// join - объединяет все элементы массива в строку, используя указанный разделитель
let productString = productList.join(", ");

console.log(productString);

// split - разбивает строку на массив подстрок, используя указанный разделитель
let newProductList = productString.split(", ");
console.log(newProductList);

