// ✅ ИСПРАВЛЕННЫЙ ВАРИАНТ

let badLetter = "р";
let words = ["привет", "мир", "работа", "отдых", "книга", "бронетранспортер"];
let badWords = [];
for (let word of words) {
  let isBad = word.toLowerCase().includes(badLetter);

  if (isBad) {
    badWords.push(word);

    // Сначала доделываем работу по подсчету
    let rCount = 0;
    for (let char of word) {
      if (char.toLowerCase() === badLetter) rCount++;
    }
    console.log(`Слово "${word}" содержит ${rCount} буквы "${badLetter}"`);
  }

  // Только в САМОМ КОНЦЕ итерации проверяем лимит
  if (badWords.length >= 3) {
    console.warn("Лимит исчерпан!");
    break;
  }
}

