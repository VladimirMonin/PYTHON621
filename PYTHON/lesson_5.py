# split() - метод строк, который разделяет строку на части по заданному разделителю и возвращает список этих частей.

users_films = input("Введите ваши любимые фильмы через запятую: ")
films_list = users_films.split(", ")  # Разделяем строку по запятой и пробелу
print(films_list)  # Выводит список фильмов, введенных пользователем

# МЕТОД JOIN = МЕТОД СТРОКИ!!!!!
# ", ".join(films_list) Так как это метод строк, мы применяем еко к строке, которая станет будущем разделителем между бывшими элементами списка. В данном случае, мы используем ", " в качестве разделителя между фильмами в итоговой строке.

films_string = ", ".join(
    films_list
)  # Объединяем список фильмов в строку с разделителем ", "
print(films_string)  # Выводит строку с фильмами, разделенными запятой и пробелом

