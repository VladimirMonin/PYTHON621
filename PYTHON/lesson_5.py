# PRACTICE - список продуктов, разделитель ; и вывод циклом
# 1. Получить строку от пользователя с помощью input()
# 2. Разбить строку на продукты с помощью split(";")
# 3. Вывести каждый продукт на новой строке с помощью цикла for

user_products = input("Введите список продуктов, разделенных точкой с запятой: ")
products_list = user_products.split(" ;")  # Разбиваем строку на продукты по раздел

# У меня получился список формата ["продукт1", " продукт2", " продукт3"] с пробелами в начале каждого продукта, кроме первого. Чтобы избавиться от этих пробелов, можно использовать метод strip() для каждого элемента списка.

clear_products_list = []

for product in products_list:
    clear_product = product.strip()  # Убираем пробелы в начале и конце строки
    clear_products_list.append(
        clear_product
    )  # Добавляем очищенный продукт в новый список


clear_products_list = [
    product.strip() for product in products_list
]  # Список с очищенными продуктами
