# Тернарный оператор - это оператор, который позволяет записать условное выражение в одну строку. Он имеет синтаксис: value_if_true if condition else value_if_false
age = 20
result = "Совершеннолетний" if age > 18 else "Несовершеннолетний"
print(result)

