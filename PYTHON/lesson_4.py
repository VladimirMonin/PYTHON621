# Диапазоны чисел можно проверять сокращенным синтаксисом. Например, если мы хотим проверить, что число x находится в диапазоне от 1 до 10, мы можем написать: 1 < x < 10. Это эквивалентно написанию: x > 1 and x < 10.

input_mark = input("Введите оценку от 1 до 100: ")

if not input_mark.isdigit():  # Проверяем, что введенное значение является числом
    print("Пожалуйста, введите число!")
    input("Нажмите Enter для выхода...")
    exit(
        1
    )  # Завершаем программу, если введенное значение не является числом 1 - это код ошибки, который означает, что программа завершилась с ошибкой

mark = int(input_mark)  # Преобразуем строку в целое число
print(type(mark))  # Проверяем тип данных, должно быть <class 'int'>

if 0 < mark < 20:
    print("Оценка: 1")
elif 20 <= mark < 40:
    print("Оценка: 2")
elif 40 <= mark < 60:
    print("Оценка: 3")
elif 60 <= mark < 80:
    print("Оценка: 4")
elif 80 <= mark <= 100:
    print("Оценка: 5")
else:
    print("Оценка должна быть от 1 до 100!")

input("Нажмите Enter для выхода...")
exit(0)

