# Приведение к Boolean - это процесс преобразования другого типа данных в логический тип данных. В Python существуют правила, по которым определенные значения считаются ложными (False), а все остальные - истинными (True).

print(bool(0))  # False
print(bool(1))  # True
print(bool(-1))  # True
print(bool(""))  # False
print(bool("Hello"))  # True
print(bool([]))  # False
print(bool([1, 2, 3]))  # True
print(bool({}))  # False
print(bool({"key": "value"}))  # True
print(bool(None))  # False


# Операторы сравнения - это операторы, которые сравнивают два значения и возвращают логическое значение (True или False). Например, == (равно), != (не равно), > (больше), < (меньше), >= (больше или равно), <= (меньше или равно)

print(5 == 5)  # True
print(5 != 5)  # False
print(5 > 3)  # True
print(5 < 3)  # False
print(5 >= 5)  # True
print(5 <= 4)  # False
print(
    5 == 5.0
)  # True - в Python 3 числа с плавающей точкой и целые числа сравниваются по значению, а не по типу
print(5 == "5")  # False - строка "5" не равна числу 5
print("пирожок" == "пирожок")  # True - строки сравниваются по содержимому, а не по типу
print("Пирожок" == "пирожок")  # False - строки сравниваются с учетом регистра
print(
    "пиро" > "пирожок"
)  # False - строки сравниваются по лексикографическому порядку, и "пиро" меньше "пирожок"

