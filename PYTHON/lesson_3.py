# Индексация в строках начинается с нуля. Первая буква в строке идет под индексом 0, вторая - под индексом 1 и т.д. Мы можем обратиться к символу строки по его индексу, используя квадратные скобки [].

alphabet = "абвгд"
print(alphabet[0])  # Выводит 'а'
print(alphabet[1])  # Выводит 'б'
print(alphabet[2])  # Выводит 'в'
# alphabet[0] = "я" # TypeError: 'str' object does not support item assignment - строки неизменяемые, мы не можем изменить символ строки по индексу, но мы можем создать новую строку, используя срезы и конкатенацию

alphabet = "абвггд"
# find rfind
print(alphabet.find("г"))  # Выводит 3 - индекс первого вхождения символа "г"
print(alphabet.rfind("г"))  # Выводит 4 - индекс последнего

menu = "Пицца, Суши, Роллы, Суши, Бургер"
