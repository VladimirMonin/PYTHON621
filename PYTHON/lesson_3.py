# Методы строк - это функции, которые принадлежат строкам и позволяют выполнять определенные операции над ними. Например, метод .upper() преобразует все символы строки в верхний регистр, а метод .lower() - в нижний регистр.

# upper(str) - преобразует строку в верхний регистр
# lower(str) - преобразует строку в нижний регистр
# capitalize(str) - преобразует первый символ строки в верхний регистр, а остальные - в нижний
# title(str) - преобразует первый символ каждого слова в верхний регистр, а остальные - в нижний
# strip(str) - удаляет пробелы в начале и в конце строки
# replace(str, old, new) - заменяет все вхождения подстроки old на новую подстроку new
# split(str, sep) - разбивает строку на список подстрок, используя разделитель sep
# join(str, iterable) - объединяет элементы итерируемого объекта в строку, используя строку str в качестве разделителя
# lstrip(str) - удаляет пробелы в начале строки
# rstrip(str) - удаляет пробелы в конце строки
# isalpha(str) - возвращает True, если все символы в строке являются буквами, иначе False
# isdigit(str) - возвращает True, если все символы в строке являются цифрами,
# isalnum(str) - возвращает True, если все символы в строке являются буквами или цифрами, иначе False
# startswith(str, prefix) - возвращает True, если строка начинается с подстроки prefix, иначе False
# endswith(str, suffix) - возвращает True, если строка заканчивается на подстроку suffix, иначе False

# len(str) - возвращает длину строки (количество символов в строке)
# count(str, sub) - возвращает количество вхождений подстроки sub в строку str
# find(str, sub) - возвращает индекс первого вхождения подстроки sub в строку str, или -1, если подстрока не найдена
# rfind(str, sub) - возвращает индекс последнего вхождения подстроки sub в строку str, или -1, если подстрока не найдена
# index(str, sub) - возвращает индекс первого вхождения подстроки sub в


full_string = "Хороша ложка к обеду"

print(full_string.upper())
print(full_string.replace("ложка", "вилка"))

# В цепочке вызова методов важен порядок - если мы сначала вызовем .upper(), а потом .replace(), то мы не найдем подстроку "ложка", так как она будет в верхнем регистре - "ЛОЖКА"
print(full_string.upper().replace("ложка", "вилка"))  # Не найдет
print(
    full_string.replace("ложка", "вилка").upper()
)  # Найдет и заменит, а потом преобразует в верхний регистр

print(id(full_string))  # Выводит уникальный идентификатор объекта в памяти
full_string = full_string.replace("ложка", "вилка")
print(
    id(full_string)
)  # Выводит уникальный идентификатор объекта в памяти - он будет другим, так как строки неизменяемые, и при замене создается новый объект в памяти

