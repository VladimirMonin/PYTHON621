"""
В Python для работы с кодами символов существуют две основные встроенные функции:

1. `ord(char)` — принимает символ и возвращает его целочисленный код (Unicode code point).
2. `chr(code)` — принимает целочисленный код и возвращает соответствующий ему символ.

Что касается системы кодирования, в современных версиях Python (начиная с Python 3) строки по умолчанию являются последовательностью символов Unicode. Это означает, что независимо от операционной системы (Windows, macOS или Linux), функции `ord()` и `chr()` оперируют таблицей Unicode (а не кодировкой файла или локальными таблицами кодировок вроде Windows-1251).

Хотя на Windows в некоторых устаревших API до сих пор может встречаться кодировка «по умолчанию», в контексте самого языка Python вы всегда работаете с Unicode (UTF-8 является стандартным стандартом для сохранения файлов в Python 3, но логика работы функций `ord` и `chr` привязана именно к спецификации Unicode).
"""

