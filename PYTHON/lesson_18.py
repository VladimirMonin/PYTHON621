key = 8

encode_message = ""

for char in message:
    # Получаем индекс буквы
    letter_index = ord(char)
    # Сдвигаем букву
    letter_index += key
    # Добавляем сдвинутую букву в строку кодирования
    encode_message += chr(letter_index)

print(encode_message)

