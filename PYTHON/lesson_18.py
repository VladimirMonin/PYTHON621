import json

"""
В Python для работы с JSON используются четыре основных метода модуля json: dump, dumps, load и loads.

Метод dump записывает объект Python в файл в формате JSON. Он принимает на вход объект и файловый дескриптор, сохраняя данные на диск в структурированном виде.

Метод dumps преобразует объект Python в строку формата JSON. Это удобно, когда нужно передать данные по сети, вывести их в лог или просто подготовить сериализованные данные внутри программы без создания файла.

Метод load считывает данные из файла JSON и преобразует их в соответствующие объекты Python, такие как словари или списки. Он принимает файловый дескриптор, открытый для чтения.

Метод loads выполняет обратную операцию для метода dumps: он принимает строку, содержащую JSON-данные, и десериализует её в структуру данных Python. Это основной способ обработки ответов от REST API или чтения конфигураций из строковых переменных.

s - строка. Таким образом то что кончается на S - это для работы со строками. А иные 2 это для файлов
"""

config = {
    "baseURL": "https://polza.ai/api/v1",
    "api_key": "парам_парам_пам!",
    "model": "z-ai/glm-5.2",
    "image": False,
}

config_path = "./config.json"

with open(config_path, "w", encoding="utf-8") as file:
    json.dump(config, file)

with open(config_path, "w", encoding="utf-8") as file:
    json.dump(config, file, ensure_ascii=False, indent=4)

with open(config_path, "r", encoding="utf-8") as file:
    config = json.load(file)
    print(config)
    print(type(config))
    print(config["api_key"])


"""
В Python при записи JSON в функции `dump` есть настройка, которая называется `ensure_ascii`. По умолчанию она установлена в `True`. Это означает, что в Python, в угоду совместимости, включена конвертация всего, что не соответствует таблице ASCII. Символы преобразуются в escape-последовательности, состоящие из поддерживаемых ASCII-символов. Это сделано для совместимости с древними системами логирования, терминалами, протоколами и прочим.

Важный момент: символы не ломаются, они просто конвертируются в последовательности, которые поддерживает ASCII, и могут быть превращены обратно в исходные буквы. Однако проблема в том, что, если мы берем одну букву в кодировке UTF-8, она обычно занимает 2 байта, а в escape-виде — уже 6 байт. То есть, если ваша задача — переслать 100 КБ текстовой информации, она легким движением руки превращается в 300 КБ. Размер данных увеличивается ровно в 3 раза. Также вы теряете читаемость текста, что, конечно же, немаловажно.

Поэтому я очень рекомендую при записи JSON-файлов или при отправке данных с сервера на клиент в браузер обязательно выключать `ensure_ascii=False`. Также вы можете использовать параметр `indent=4`, который задаст красивые отступы.
"""

json_string = """{
    "baseURL": "https://polza.ai/api/v1",
    "api_key": "парам_парам_пам!",
    "model": "z-ai/glm-5.2",
    "image": false
}"""

python_obj = json.loads(json_string)
print(python_obj)
print(type(python_obj))

print(json.dumps(python_obj, ensure_ascii=False))